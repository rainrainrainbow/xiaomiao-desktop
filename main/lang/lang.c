static lang_id_t s_current_lang = LANG_ZH;

void lang_set(lang_id_t lang)
{
    if (lang >= LANG_MAX) return;
    s_current_lang = lang;
    ESP_LOGI(TAG, "Language set to %s", lang == LANG_ZH ? "中文" : "English");
}

lang_id_t lang_get_current(void)
{
    return s_current_lang;
}

const char* lang_get(str_id_t id)
{
    if (id >= STR_COUNT) return "";
    
    /* 当 FreeType 字体未就绪时，强制使用英文（英文不需要中文字体）。
     * 注意：仅当 FreeType 字体确实不可用且当前语言为中文时降级。
     * 如果用户明确选择了中文但字体不可用，显示英文是为了避免乱码。 */
    extern bool lv_freetype_font_is_ready(void);
    if (!lv_freetype_font_is_ready() && s_current_lang == LANG_ZH) {
        /* 字体不可用，降级为英文 */
        const char *str = s_en[id];
        return str ? str : "";
    }
    
    const char *str = NULL;
    switch (s_current_lang) {
    case LANG_EN:
        str = s_en[id];
        break;
    case LANG_ZH:
    default:
        str = s_zh[id];
        break;
    }
    return str ? str : "";
}